import assert from 'node:assert/strict';
import {openWorld} from './lib/enforce-world.mjs';
const world=await openWorld({gameSettings:{locale:'zh-CN',dicePolicy:'real_allowed'}});
const {skipCurrentTurn}=await import('../src/lib/dm/encounter-tools.ts');
const {listRecentMessages}=await import('../src/lib/db/messages.ts');
const {updateGameSettings}=await import('../src/lib/db/campaigns.ts');
const hero=world.addHero({name:'Authored 米拉',class:'fighter',level:2,abilities:{dex:18},maxHp:30});
await world.beginFight([{monster:'goblin',count:1}],{heroFaces:{[hero.id]:18},enemyFace:4});
assert.equal(skipCurrentTurn(world.campaignId),true);
let notices=listRecentMessages(world.campaignId,100).filter(m=>m.authorType==='system');
assert(notices.some(m=>/队长跳过了Authored 米拉的回合/.test(m.content)));
const old=notices.find(m=>/队长跳过/.test(m.content));
updateGameSettings(world.campaignId,{locale:'en'});
assert.equal(skipCurrentTurn(world.campaignId),true);
notices=listRecentMessages(world.campaignId,100).filter(m=>m.authorType==='system');
assert(notices.some(m=>/^The party lead skipped .+'s turn\. It is now .+'s turn\./.test(m.content)));
assert.equal(notices.find(m=>m.id===old.id).content,old.content);
await world.close();
console.log('PASS: new turn notices follow campaign locale, preserve authored names and English wording; old Chinese history stays unchanged.');
